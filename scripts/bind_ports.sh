#!/usr/bin/env bash
# Create stable device names /dev/so101_follower and /dev/so101_leader.
#
# /dev/ttyACM0 and /dev/ttyACM1 can swap after a reboot or replug. This script
# identifies each arm's board by its USB serial number (or USB port position if
# the board has no unique serial) and writes a udev rule with fixed symlinks.
set -euo pipefail

RULES_FILE=/etc/udev/rules.d/99-so101-names.rules

list_ports() { ls /dev/ttyACM* /dev/ttyUSB* 2>/dev/null | sort || true; }

detect_arm() {  # detect_arm <name>  -> prints the new tty device
    local name="$1" before after new
    read -r -p "Unplug the USB cable of BOTH arms, then press Enter... " _
    before="$(list_ports)"
    read -r -p "Now plug in ONLY the $name arm (USB + power) and press Enter... " _
    sleep 2
    after="$(list_ports)"
    new="$(comm -13 <(echo "$before") <(echo "$after") | head -n1)"
    [[ -n "$new" ]] || { echo "No new serial device detected for $name." >&2; exit 1; }
    echo "$new"
}

udev_prop() { udevadm info -q property -n "$1" | sed -n "s/^$2=//p"; }

match_for() {  # match_for <dev>  -> udev match expression
    local dev="$1" serial path
    serial="$(udev_prop "$dev" ID_SERIAL_SHORT)"
    path="$(udev_prop "$dev" ID_PATH)"
    if [[ -n "$serial" ]]; then
        echo "ENV{ID_SERIAL_SHORT}==\"$serial\""
    else
        echo "ENV{ID_PATH}==\"$path\""
    fi
}

echo "== SO-101 port binding =="
f_dev="$(detect_arm follower)"; f_match="$(match_for "$f_dev")"
echo "Follower -> $f_dev ($f_match)"
l_dev="$(detect_arm leader)";   l_match="$(match_for "$l_dev")"
echo "Leader   -> $l_dev ($l_match)"

if [[ "$f_match" == "$l_match" ]]; then
    echo "Both boards report the same serial number - binding by USB port position instead."
    echo "Keep each arm plugged into the SAME USB port from now on."
    f_match="ENV{ID_PATH}==\"$(udev_prop "$f_dev" ID_PATH)\""
    l_match="ENV{ID_PATH}==\"$(udev_prop "$l_dev" ID_PATH)\""
fi

sudo tee "$RULES_FILE" >/dev/null <<EOF
# Generated by scripts/bind_ports.sh
SUBSYSTEM=="tty", $f_match, SYMLINK+="so101_follower", MODE="0666"
SUBSYSTEM=="tty", $l_match, SYMLINK+="so101_leader", MODE="0666"
EOF
sudo udevadm control --reload-rules
sudo udevadm trigger --subsystem-match=tty
sleep 1

echo
echo "Wrote $RULES_FILE. Plug in both arms; you should now see:"
ls -l /dev/so101_* 2>/dev/null || echo "  (symlinks appear once the arms are plugged in)"
echo
echo "Set in config/so101.env:"
echo "  FOLLOWER_PORT=/dev/so101_follower"
echo "  LEADER_PORT=/dev/so101_leader"
